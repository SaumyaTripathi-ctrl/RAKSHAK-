"""Vectors that pin the C edge rules (firmware/common/src/rk_edge.c) to the Python reference (rakshak_ml.edge).

    python tools/gen_edge_vectors.py            # rewrite the vectors
    python tools/gen_edge_vectors.py --check    # fail if the committed files are stale

Outputs firmware/common/spec/edge_vectors.json and firmware/common/test/edge_vectors.h.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
from rakshak_ml.edge import FanController, flap_for_deviation

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "firmware/common/spec/edge_vectors.json"
HEADER_PATH = ROOT / "firmware/common/test/edge_vectors.h"

STEP_MIN = 5.0


def run_fan(series: list[float]) -> list[int]:
    fan = FanController()
    return [int(fan.update(i * STEP_MIN, v)) for i, v in enumerate(series)]


def sequences() -> dict[str, list[float]]:
    rng = np.random.default_rng(3)
    piecewise = (
        [20.0] * 40
        + [20.0 + 1.2 * i for i in range(30)]
        + [56.0] * 30
        + [56.0 - 1.5 * i for i in range(20)]
        + [26.0] * 60
    )
    noisy_long = [round(float(v + rng.normal(0, 1.0)), 1) for v in piecewise]
    return {
        "rising_then_flat": [10 + 1.0 * i for i in range(8)] + [17.0] * 12,
        "flat_noise_only": [20, 21.2, 19.4, 20.8, 19.9, 21.0, 19.6, 20.5, 20.1, 20.9, 19.8, 20.3],
        "rise_fall_stable": [0, 2, 4, 6, 8, 10, 12, 14] + [14 - 2 * i for i in range(6)] + [4.0] * 16,
        "noisy_long_run": noisy_long,
    }


def build() -> dict:
    seqs = sequences()
    flap_cases = []
    for upper in (13.0, 4.0, 2.0):
        for d in (-5, -0.01, 0, 0.01, 1.49, 1.5, 1.51, 2.99, 3.0, 3.01, 8):
            flap_cases.append({"temp": round(upper + d, 2), "upper": upper, "flap": flap_for_deviation(round(upper + d, 2), upper)})
    return {
        "note": "Generated by tools/gen_edge_vectors.py from rakshak_ml.edge. Do not edit.",
        "step_min": STEP_MIN,
        "fan": {name: {"series": s, "expected": run_fan(s)} for name, s in seqs.items()},
        "flap": flap_cases,
    }


def render_header(v: dict) -> str:
    out = ["/* GENERATED by tools/gen_edge_vectors.py - do not edit. */", "#ifndef RK_EDGE_VECTORS_H", "#define RK_EDGE_VECTORS_H"]
    out.append(f"#define EV_STEP_MIN {v['step_min']}")
    names = list(v["fan"])
    for n in names:
        s = v["fan"][n]
        out.append(f"static const double EV_{n.upper()}_SERIES[] = {{{', '.join(repr(float(x)) for x in s['series'])}}};")
        out.append(f"static const int EV_{n.upper()}_EXPECTED[] = {{{', '.join(str(x) for x in s['expected'])}}};")
    out.append("typedef struct { const char *name; const double *series; const int *expected; int n; } ev_fan_case_t;")
    out.append("static const ev_fan_case_t EV_FAN_CASES[] = {")
    for n in names:
        out.append(f'  {{"{n}", EV_{n.upper()}_SERIES, EV_{n.upper()}_EXPECTED, {len(v["fan"][n]["series"])}}},')
    out.append("};")
    out.append("#define EV_FAN_CASES_N (sizeof EV_FAN_CASES / sizeof EV_FAN_CASES[0])")
    out.append("typedef struct { double temp, upper; int flap; } ev_flap_t;")
    out.append("static const ev_flap_t EV_FLAP[] = {")
    for c in v["flap"]:
        out.append(f"  {{{c['temp']!r}, {c['upper']!r}, {c['flap']}}},")
    out.append("};")
    out.append("#define EV_FLAP_N (sizeof EV_FLAP / sizeof EV_FLAP[0])")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    v = build()
    js, hd = json.dumps(v, indent=2) + "\n", render_header(v)
    if a.check:
        stale = [
            p.name
            for p, t in ((JSON_PATH, js), (HEADER_PATH, hd))
            if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != t
        ]
        if stale:
            print("stale edge vectors:", ", ".join(stale), "- run tools/gen_edge_vectors.py", file=sys.stderr)
            return 1
        print("edge vectors up to date")
        return 0
    JSON_PATH.write_text(js, encoding="utf-8", newline="\n")
    HEADER_PATH.write_text(hd, encoding="utf-8", newline="\n")
    print(f"wrote {JSON_PATH.relative_to(ROOT)} and {HEADER_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
