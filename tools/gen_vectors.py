"""Generate the cross-language test vectors from the Python reference codec.

Outputs:
  firmware/common/spec/vectors.json   - human-readable, consumed by the Python tests
  firmware/common/test/vectors.h      - consumed by the C host test

Run ``python tools/gen_vectors.py`` after any spec change; ``--check`` fails if the committed files
are stale (used by CI and the Python tests).
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import fields
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "backend"))

from rakshak.codec import (
    Event,
    HubSample,
    TagSample,
    derive_device_key,
    encode_frame,
    hkdf_sha256,
    make_nonce,
    spec,
)
from rakshak.codec.record import pack_body
from rakshak.ledger.merkle import merkle_proof, merkle_root

JSON_PATH = ROOT / "firmware/common/spec/vectors.json"
HEADER_PATH = ROOT / "firmware/common/test/vectors.h"

MASTER = bytes(range(32))
T0 = 1_791_000_000  # 2026-10-03T03:20:00Z, arbitrary fixed epoch

TAG, HUB = "TAG-0001", "HUB-0001"
SHIP = "RKS-26-000418"

# (name, record, key_epoch); order matters: chains are built per device in this order.
CASES: list[tuple[str, object, int]] = [
    ("tag_0_first_genesis", TagSample(TAG, SHIP, 0, T0, 2845, 8800, 340, 0b10, 87), 0),
    ("tag_1", TagSample(TAG, SHIP, 1, T0 + 60, 2851, 8790, 342, 0b10, 87), 0),
    (
        "tag_2_lid_open_negative_temp",
        TagSample(TAG, SHIP, 2, T0 + 120, -150, 9999, 1000, 0b11, 86),
        0,
    ),
    ("tag_3_unsynced_clock", TagSample(TAG, SHIP, 3, 300, 3000, 7500, 0, 0b00, 86), 0),
    ("event_time_sync", Event(TAG, SHIP, 4, T0 + 600, 1, 300, 0, 0b10, 86), 0),
    (
        "hub_0_gps_fan",
        HubSample(HUB, SHIP, 0, T0, 3120, 6500, 40, 16_990_000, 73_300_000, 0b1110, 25, 92, 1),
        0,
    ),
    (
        "hub_1_southern_western_hemisphere",
        HubSample(
            HUB, SHIP, 1, T0 + 300, 2990, 6400, 175, -33_868_800, -151_209_300, 0b0110, 0, 92, 0
        ),
        0,
    ),
    ("tag_key_epoch_1", TagSample("TAG-0002", SHIP, 0, T0, 2500, 9000, 100, 0b10, 100), 1),
]

RFC5869_A1 = {
    "ikm": bytes([0x0B] * 22),
    "salt": bytes(range(0x0D)),
    "info": bytes(range(0xF0, 0xFA)),
    "okm": bytes.fromhex(
        "3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865"
    ),
}


def _hex(b: bytes) -> str:
    return b.hex()


def build() -> dict:
    # RFC 5869 A.1 requires salt/len=42: check our hkdf against the published vector.
    got = hkdf_sha256(RFC5869_A1["ikm"], RFC5869_A1["info"], 42, RFC5869_A1["salt"])
    assert got == RFC5869_A1["okm"], "hkdf_sha256 does not match RFC 5869 A.1"

    chains: dict[str, bytes] = {}
    records = []
    device_keys = {}
    for name, rec, epoch in CASES:
        key = derive_device_key(MASTER, rec.device_id, epoch)
        device_keys[(rec.device_id, epoch)] = key
        prev = chains.get(rec.device_id, spec.GENESIS_HASH)
        frame, h = encode_frame(rec, prev, key, epoch)
        chains[rec.device_id] = h
        records.append(
            {
                "name": name,
                "type": int(rec.TYPE),
                "fields": {f.name: getattr(rec, f.name) for f in fields(rec)},
                "key_epoch": epoch,
                "nonce": _hex(make_nonce(rec.seq)),
                "prev_hash": _hex(prev),
                "body": _hex(pack_body(rec)),
                "hash": _hex(h),
                "frame": _hex(frame),
            }
        )

    first = records[0]
    frame = bytearray(bytes.fromhex(first["frame"]))
    flipped_ct = bytearray(frame)
    flipped_ct[spec.HEADER_LEN + 5] ^= 0x01
    flipped_hdr = bytearray(frame)
    flipped_hdr[2] ^= 0x01  # device_id byte is AAD
    flipped_tag = bytearray(frame)
    flipped_tag[-1] ^= 0x80
    wrong_epoch = bytearray(frame)
    wrong_epoch[18] ^= 0x01  # key_epoch is AAD; also selects a different key

    import hashlib

    leaves = [hashlib.sha256(bytes([i])).digest() for i in range(9)]
    merkle = {
        "note": "RFC 6962 construction: leaf=SHA256(0x00||h), node=SHA256(0x01||l||r); leaves are sha256(bytes([i]))",
        "leaves": [_hex(x) for x in leaves],
        "roots": {str(n): _hex(merkle_root(leaves[:n])) for n in range(0, 10) if n <= len(leaves)},
        "proof_case": {
            "n": 7,
            "index": 4,
            "proof": [{"hash": _hex(h), "side": side} for h, side in merkle_proof(leaves[:7], 4)],
        },
    }

    return {
        "spec_version": spec.VERSION,
        "note": "Generated by tools/gen_vectors.py from the Python reference codec. Do not edit.",
        "sizes": {
            "tag_body": spec.BODY_LEN[spec.RecordType.TAG_SAMPLE],
            "hub_body": spec.BODY_LEN[spec.RecordType.HUB_SAMPLE],
            "event_body": spec.BODY_LEN[spec.RecordType.EVENT],
            "header": spec.HEADER_LEN,
            "tag_frame": spec.FRAME_LEN[spec.RecordType.TAG_SAMPLE],
            "hub_frame": spec.FRAME_LEN[spec.RecordType.HUB_SAMPLE],
            "event_frame": spec.FRAME_LEN[spec.RecordType.EVENT],
        },
        "master_key": _hex(MASTER),
        "hkdf_rfc5869_a1": {k: _hex(v) for k, v in RFC5869_A1.items()},
        "device_keys": [
            {"device_id": d, "key_epoch": e, "key": _hex(k)} for (d, e), k in device_keys.items()
        ],
        "merkle": merkle,
        "records": records,
        "negative": [
            {
                "name": "flipped_ciphertext_bit",
                "device_id": TAG,
                "key_epoch": 0,
                "frame": _hex(flipped_ct),
            },
            {
                "name": "flipped_header_bit_aad",
                "device_id": TAG,
                "key_epoch": 0,
                "frame": _hex(flipped_hdr),
            },
            {
                "name": "flipped_gcm_tag_bit",
                "device_id": TAG,
                "key_epoch": 0,
                "frame": _hex(flipped_tag),
            },
            {
                "name": "key_epoch_mismatch",
                "device_id": TAG,
                "key_epoch": 0,
                "frame": _hex(wrong_epoch),
            },
        ],
    }


def render_header(v: dict) -> str:
    out = [
        "/* GENERATED by tools/gen_vectors.py - do not edit. */",
        "#ifndef RK_VECTORS_H",
        "#define RK_VECTORS_H",
        "#include <stdint.h>",
        '#define VEC_MASTER_KEY "%s"' % v["master_key"],
        "typedef struct { const char *ikm, *salt, *info, *okm; } vec_hkdf_t;",
        "static const vec_hkdf_t VEC_HKDF = {%s};"
        % ", ".join('"%s"' % v["hkdf_rfc5869_a1"][k] for k in ("ikm", "salt", "info", "okm")),
        "typedef struct { const char *device_id; unsigned key_epoch; const char *key; } vec_key_t;",
        "static const vec_key_t VEC_KEYS[] = {",
    ]
    for k in v["device_keys"]:
        out.append('  {"%s", %d, "%s"},' % (k["device_id"], k["key_epoch"], k["key"]))
    out += [
        "};",
        "#define VEC_KEYS_N (sizeof VEC_KEYS / sizeof VEC_KEYS[0])",
        "typedef struct {",
        "  const char *name; int type; const char *device_id; const char *shipment_id;",
        "  uint32_t seq, ts; int64_t f[9]; unsigned key_epoch;",
        "  const char *nonce, *prev_hash, *body, *hash, *frame;",
        "} vec_record_t;",
        "static const vec_record_t VEC_RECORDS[] = {",
    ]
    for r in v["records"]:
        f = r["fields"]
        rest = [
            val for key, val in f.items() if key not in ("device_id", "shipment_id", "seq", "ts")
        ]
        rest += [0] * (9 - len(rest))
        out.append(
            '  {"%s", %d, "%s", "%s", %du, %du, {%s}, %d, "%s", "%s", "%s", "%s", "%s"},'
            % (
                r["name"],
                r["type"],
                f["device_id"],
                f["shipment_id"],
                f["seq"],
                f["ts"],
                ", ".join(str(x) for x in rest),
                r["key_epoch"],
                r["nonce"],
                r["prev_hash"],
                r["body"],
                r["hash"],
                r["frame"],
            )
        )
    out += [
        "};",
        "#define VEC_RECORDS_N (sizeof VEC_RECORDS / sizeof VEC_RECORDS[0])",
        "typedef struct { const char *name, *device_id; unsigned key_epoch; const char *frame; } vec_neg_t;",
        "static const vec_neg_t VEC_NEG[] = {",
    ]
    for n in v["negative"]:
        out.append(
            '  {"%s", "%s", %d, "%s"},' % (n["name"], n["device_id"], n["key_epoch"], n["frame"])
        )
    out += ["};", "#define VEC_NEG_N (sizeof VEC_NEG / sizeof VEC_NEG[0])", "#endif", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if committed vectors are stale")
    args = ap.parse_args()
    v = build()
    js = json.dumps(v, indent=2) + "\n"
    hd = render_header(v)
    if args.check:
        stale = [
            p.name
            for p, txt in ((JSON_PATH, js), (HEADER_PATH, hd))
            if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != txt
        ]
        if stale:
            print("stale vectors:", ", ".join(stale), "- run tools/gen_vectors.py", file=sys.stderr)
            return 1
        print("vectors up to date")
        return 0
    JSON_PATH.write_text(js, encoding="utf-8", newline="\n")
    HEADER_PATH.write_text(hd, encoding="utf-8", newline="\n")
    print(f"wrote {JSON_PATH.relative_to(ROOT)} and {HEADER_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
